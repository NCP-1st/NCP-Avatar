_REINFORCE_DEFAULT = "공감과 열린 질문 중심으로만 답하세요."


def build_reinforcement(violations: list[str]) -> str:
    """위반한 규칙에 맞는 재작성 지시를 만든다.

    위반과 무관한 지시까지 같이 주면 모델이 엉뚱한 데를 고친다. 예를 들어
    과거 추측 때문에 재생성하는데 "병명을 빼라"고만 하면 그대로 다시 낸다.
    """
    lines = [
        _REINFORCE_BY_RULE[rule] for rule in dict.fromkeys(violations)
        if rule in _REINFORCE_BY_RULE
    ]
    body = "\n".join(f"- {line}" for line in lines) or f"- {_REINFORCE_DEFAULT}"
    return _REINFORCE_HEADER.format(violations=", ".join(violations)) + "\n" + body


# --- 사용자 메시지 조립 ----------------------------------------------------


def build_context_prompt(message: str, history: list[CounselTurn]) -> str:
    """챗봇 에이전트(사건·감정 구조화)에 보낼 메시지."""
    parts: list[str] = []
    if history:
        parts.append("# 대화 이력 (참고용)\n" + _format_history(history, limit=4))
    parts.append(f"# 분석 대상 — 사용자의 마지막 메시지\n{message}")
    return "\n\n".join(parts)


def build_counselor_prompt(
    message: str,
    state: ConversationState | None,
    snippets: list[KnowledgeSnippet],
    facts: list[OntologyFact],
    history: list[CounselTurn],
) -> str:
    """상담가 에이전트에 보낼 메시지."""
    parts: list[str] = []

    if state is not None:
        parts.append(
            "# 분석된 사건·감정\n"
            + json.dumps(
                {
                    "events": [
                        {
                            "summary": event.summary,
                            "people": event.people,
                            "place": event.place,
                            "when": event.when_hint,
                        }
                        for event in state.events
                    ],
                    "emotion": {
                        "primary": state.emotion.primary,
                        "secondary": state.emotion.secondary,
                        "intensity": state.emotion.intensity,
                        "confidence": round(state.emotion.confidence, 2),
                        "evidence": state.emotion.evidence,
                    },
                },
                ensure_ascii=False,
            )
        )

        # 질문을 넣을지 말지는 이걸로 정한다. 없으면 묻지 않는다.
        if state.unclear_point:
            parts.append("# 아직 모르는 것\n" + state.unclear_point)
        else:
            parts.append(
                "# 아직 모르는 것\n"
                "없습니다. 사용자가 충분히 이야기했습니다. "
                "굳이 더 캐묻지 말고 받아주세요."
            )

    if history:
        parts.append("# 대화 이력\n" + _format_history(history, limit=6))

    if snippets:
        parts.append(
            "# 상담 지식 (참고용, 인용 금지)\n"
            + "\n".join(f"- {s.title}: {s.content}" for s in snippets)
        )

    if facts:
        parts.append(
            "# 관계 정보\n"
            + json.dumps(
                [
                    {
                        "subject": fact.subject,
                        "relation": fact.relation,
                        "object": fact.object,
                        "observed": fact.observed,
                    }
                    for fact in facts
                ],
                ensure_ascii=False,
            )
        )

    parts.append(f"# 사용자의 현재 메시지\n{message}")
    return "\n\n".join(parts)


def _format_history(history: list[CounselTurn], *, limit: int) -> str:
    return "\n".join(
        f"{'사용자' if turn.role == 'user' else '상담사'}: {turn.content}"
        for turn in history[-limit:]
    )
